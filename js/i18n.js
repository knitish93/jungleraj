function jrGetLang() {
  return localStorage.getItem(JR_I18N_KEY) || 'hi';
}

function jrSetLang(lang) {
  localStorage.setItem(JR_I18N_KEY, lang);
  jrApplyLang(lang);
}

function jrT(key, lang) {
  lang = lang || jrGetLang();
  return (JR_DICT[lang] && JR_DICT[lang][key]) || (JR_DICT.hi[key]) || key;
}

function jrApplyLang(lang) {
  lang = lang || jrGetLang();
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', 'ltr');

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = jrT(key, lang);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.setAttribute('placeholder', jrT(key, lang));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    el.setAttribute('aria-label', jrT(key, lang));
  });

  document.querySelectorAll('.lang-toggle button').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  document.dispatchEvent(new CustomEvent('jr:langchange', { detail: { lang } }));
}

document.addEventListener('DOMContentLoaded', () => {
  const lang = jrGetLang();
  jrApplyLang(lang);
  // Set page title on initial load
  if (lang === 'hi') {
    document.title = 'जंगल राज – भारत की आवाज़ | राष्ट्रीय नागरिक डैशबोर्ड';
  } else {
    document.title = 'Jungle Raj — Voice of India | Citizen Awareness Platform';
  }
  document.querySelectorAll('.lang-toggle button[data-lang]').forEach(btn => {
    btn.addEventListener('click', () => jrSetLang(btn.getAttribute('data-lang')));
  });
});
